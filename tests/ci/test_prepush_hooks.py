def test_lock_wait_proceeds(checkout: Path, tmp_path: Path) -> None:
    lock_dir = tmp_path / "locks"
    lock_dir.mkdir()
    with (lock_dir / "pyright.lock").open("w") as held:
        fcntl.flock(held, fcntl.LOCK_EX)
        with subprocess.Popen(
            ["bash", str(GUARD), "pyright", "--", sys.executable, "-c", "print('executed')"],
            cwd=checkout,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        ) as process:
            try:
                assert process.stderr is not None
                with selectors.DefaultSelector() as selector:
                    selector.register(process.stderr, selectors.EVENT_READ)
                    assert selector.select(timeout=5), "wrapper never reported lock contention"
                assert "waiting for pyright lock" in process.stderr.readline()
                assert process.poll() is None
                fcntl.flock(held, fcntl.LOCK_UN)
                stdout, stderr = process.communicate(timeout=5)
                assert process.returncode == 0
                assert "executed" in stdout and "SKIPPED" not in stderr
            finally:
                if process.poll() is None:
                    process.kill()
                    process.wait(timeout=5)


def test_lock_timeout(checkout: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("AVA_PREPUSH_LOCK_WAIT_SECONDS", "0.01")
    lock_dir = tmp_path / "locks"
    lock_dir.mkdir()
    with (lock_dir / "pyright.lock").open("w") as held:
        fcntl.flock(held, fcntl.LOCK_EX)
