def install_fixture(repo: Path, interpreter: Path | None = None) -> Path:
    if interpreter is None:
        interpreter = repo / ".venv/bin/python"
        interpreter.symlink_to(sys.executable)
    for hook_type in ("pre-commit", "pre-push"):
        hook = repo / ".git/hooks" / hook_type
        hook.write_text(
            "#!/usr/bin/env bash\n"
            "# File generated by pre-commit: https://pre-commit.com\n"
            "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
            f"INSTALL_PYTHON={shlex.quote(str(interpreter))}\n"
            f"ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type={hook_type})\n"
        )
        hook.chmod(0o755)
    return repo / ".git/hooks/pre-push"


