def _scan(home: Path) -> subprocess.CompletedProcess[str]:
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    env["HOME"] = str(home)
    return subprocess.run(
        [sys.executable, str(CHECK), "--scan-machine"],
        env=env,
        capture_output=True,
        text=True,
        check=False,
        timeout=10,
    )


