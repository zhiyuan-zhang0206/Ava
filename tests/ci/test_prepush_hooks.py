import shutil
import subprocess
import sys
from pathlib import Path
from typing import Literal

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[2]
GUARD = ROOT / "scripts/prepush-guard.sh"
CHECK = ROOT / "scripts/provision/check_git_hooks.py"
INSTALL = ".venv/bin/pre-commit install --hook-type pre-commit --hook-type pre-push"
requires_flock = pytest.mark.skipif(shutil.which("flock") is None, reason="flock is not installed")


@pytest.fixture
def checkout(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    # Clear hook context before even initializing the temporary repository.
    for name in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR"):
        monkeypatch.delenv(name, raising=False)
    repo = tmp_path / "main clone"
    repo.mkdir()
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    monkeypatch.setenv("AVA_PREPUSH_LOCK_DIR", str(tmp_path / "locks"))
    monkeypatch.setenv("AVA_PREPUSH_MAX_LOAD_PER_CORE", "1000000")
    monkeypatch.setenv("AVA_PREPUSH_LOCK_WAIT_SECONDS", "2")
    executable = repo / ".venv/bin/pyright"
    executable.parent.mkdir(parents=True)
    executable.symlink_to(sys.executable)
    return repo


def run_guard(
    repo: Path, tool: str = "pyright", code: str = "print('executed')"
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["bash", str(GUARD), tool, "--", sys.executable, "-c", code],
        cwd=repo,
        capture_output=True,
        text=True,
        check=False,
        timeout=10,
    )


def check_install(repo: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(CHECK)],
        cwd=repo,
        capture_output=True,
        text=True,
        check=False,
        timeout=1,
    )


def install_fixture(repo: Path, interpreter: Path | None = None) -> Path:
    if interpreter is None:
        interpreter = repo / ".venv/bin/python"
        interpreter.symlink_to(sys.executable)
    for hook_type in ("pre-commit", "pre-push"):
        hook = repo / ".git/hooks" / hook_type
        hook.write_text(
            "#!/usr/bin/env bash\n"
            "# File generated by pre-commit: https://pre-commit.com\n"
            "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
            f"INSTALL_PYTHON={shlex.quote(str(interpreter))}\n"
            f"ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type={hook_type})\n"
        )
        hook.chmod(0o755)
    return repo / ".git/hooks/pre-push"


def test_stage_contract() -> None:
    config = yaml.safe_load((ROOT / ".pre-commit-config.yaml").read_text())
    assert config["default_install_hook_types"] == ["pre-commit", "pre-push"]
    hooks = {hook["id"]: hook for repo in config["repos"] for hook in repo["hooks"]}
    for name in ("pyright", "frontend-tsc", "frontend-eslint", "frontend-vitest"):
        hook = hooks[name]
        assert hook["stages"] == ["pre-push"]
        assert hook["verbose"] is True  # pre-commit hides output on PASS otherwise.
        assert "bash scripts/prepush-guard.sh " in hook["entry"]
    vitest = hooks["frontend-vitest"]
    assert vitest["entry"] == (
        "bash scripts/prepush-guard.sh vitest -- bash -c 'cd ui/web && npx --no-install vitest run'"
    )
    assert vitest["files"] == r"^ui/web/.*\.(ts|tsx)$"
    assert vitest["pass_filenames"] is False
    check = hooks["check-git-hooks-install"]
    assert check["stages"] == ["pre-commit"]
    assert check["always_run"] is True
    assert check["verbose"] is True


def test_missing_flock_skips(checkout: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    shim_dir = checkout / "no-flock"
    shim_dir.mkdir()
    bash = shutil.which("bash")
    assert bash is not None
    (shim_dir / "bash").symlink_to(bash)
    monkeypatch.setenv("PATH", str(shim_dir))
    marker = checkout / "executed"
    result = run_guard(checkout, code=f"from pathlib import Path; Path({str(marker)!r}).touch()")
    assert result.returncode == 0
    assert "PRE-PUSH SKIPPED [pyright]: flock is not installed" in result.stderr
    assert not marker.exists()


@requires_flock
def test_load_skip(checkout: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    # Fix the measured load in the probe, then force its threshold via env.
    probe_dir = checkout / "probe"
    probe_dir.mkdir()
    probe = probe_dir / "python3"
    probe.write_text(
        f"#!{sys.executable}\nimport os, sys\n"
        "os.getloadavg = lambda: (100.0, 0.0, 0.0)\nsys.argv = sys.argv[1:]\nexec(sys.stdin.read())\n"
    )
    probe.chmod(0o755)
    monkeypatch.setenv("PATH", str(probe_dir) + os.pathsep + os.environ["PATH"])
    monkeypatch.setenv("AVA_PREPUSH_MAX_LOAD_PER_CORE", "0")
    result = run_guard(checkout)
    assert result.returncode == 0
    assert "PRE-PUSH SKIPPED [pyright]" in result.stderr
    assert "load/core" in result.stderr and "threshold 0" in result.stderr
    assert "executed" not in result.stdout


@requires_flock
def test_lock_wait_proceeds(checkout: Path, tmp_path: Path) -> None:
    lock_dir = tmp_path / "locks"
    lock_dir.mkdir()
    with (lock_dir / "pyright.lock").open("w") as held:
        fcntl.flock(held, fcntl.LOCK_EX)
        with subprocess.Popen(
            ["bash", str(GUARD), "pyright", "--", sys.executable, "-c", "print('executed')"],
            cwd=checkout,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        ) as process:
            try:
                assert process.stderr is not None
                with selectors.DefaultSelector() as selector:
                    selector.register(process.stderr, selectors.EVENT_READ)
                    assert selector.select(timeout=5), "wrapper never reported lock contention"
                assert "waiting for pyright lock" in process.stderr.readline()
                assert process.poll() is None
                fcntl.flock(held, fcntl.LOCK_UN)
                stdout, stderr = process.communicate(timeout=5)
                assert process.returncode == 0
                assert "executed" in stdout and "SKIPPED" not in stderr
            finally:
                if process.poll() is None:
                    process.kill()
                    process.wait(timeout=5)


@requires_flock
def test_lock_timeout(checkout: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("AVA_PREPUSH_LOCK_WAIT_SECONDS", "0.01")
    lock_dir = tmp_path / "locks"
    lock_dir.mkdir()
    with (lock_dir / "pyright.lock").open("w") as held:
        fcntl.flock(held, fcntl.LOCK_EX)
        result = run_guard(checkout)
    assert result.returncode == 0
    assert "waiting for pyright lock" in result.stderr
    assert "PRE-PUSH SKIPPED [pyright]: lock wait timed out after 0.01s" in result.stderr
    assert "executed" not in result.stdout


