@pytest.mark.parametrize("problem", ["ephemeral", "dot-worktrees", "wrong-stage", "malformed"])
def test_precommit_drift_reports_both_hooks(checkout: Path, tmp_path: Path, problem: str) -> None:
    push_hook = install_fixture(checkout)
    commit_hook = checkout / ".git/hooks/pre-commit"
    source = commit_hook.read_text()
    if problem in ("ephemeral", "dot-worktrees"):
        directory = "worktrees" if problem == "ephemeral" else ".worktrees"
        ephemeral = tmp_path / directory / "task/.venv/bin/python"
        ephemeral.parent.mkdir(parents=True)
        ephemeral.symlink_to(sys.executable)
        source = source.replace(
            shlex.quote(str(checkout / ".venv/bin/python")), shlex.quote(str(ephemeral))
        )
    elif problem == "wrong-stage":
        source = source.replace("--hook-type=pre-commit", "--hook-type=pre-push")
    else:
        source = source.replace("INSTALL_PYTHON=", "INSTALL_PYTHON='")
    commit_hook.write_text(source)
    push_hook.chmod(0o644)
    result = check_install(checkout)
    assert result.returncode == 0
    assert str(commit_hook) in result.stdout and str(push_hook) in result.stdout
    assert result.stdout.count("WARNING:") == 2
    assert INSTALL in result.stdout


def test_valid_hook_silent_in_main_and_linked_worktree(checkout: Path, tmp_path: Path) -> None:
    install_fixture(checkout)
    subprocess.run(
        [
            "git",
            "-c",
            "user.name=Test",
            "-c",
            "user.email=test@example.com",
            "commit",
            "--allow-empty",
            "-qm",
            "fixture",
        ],
        cwd=checkout,
        check=True,
    )
    worktree = tmp_path / "linked"
    subprocess.run(
        ["git", "worktree", "add", "-qb", "linked", str(worktree)], cwd=checkout, check=True
    )
    for repo in (checkout, worktree):
        result = check_install(repo)
        assert result.returncode == 0 and result.stdout == result.stderr == ""


@pytest.mark.parametrize(
    "problem", ["unmanaged", "dead", "ephemeral", "nonexecutable", "malformed", "override"]
)
def test_broken_install_warns(
    checkout: Path,
    tmp_path: Path,
    problem: Literal["unmanaged", "dead", "ephemeral", "nonexecutable", "malformed", "override"],
) -> None:
    hook = install_fixture(checkout)
    match problem:
        case "unmanaged":
            hook.write_text("#!/bin/sh\nexit 0\n")
        case "dead":
            (checkout / ".venv/bin/python").unlink()
        case "ephemeral":
            ephemeral = tmp_path / "worktrees/task/.venv/bin/python"
            ephemeral.parent.mkdir(parents=True)
            ephemeral.symlink_to(sys.executable)
            install_fixture(checkout, ephemeral)
        case "nonexecutable":
            hook.chmod(0o644)
        case "malformed":
            hook.write_text(hook.read_text().replace("INSTALL_PYTHON=", "INSTALL_PYTHON='"))
        case "override":
            subprocess.run(
                ["git", "config", "core.hooksPath", ".custom-hooks"], cwd=checkout, check=True
            )
    result = check_install(checkout)
    assert result.returncode == 0
    assert "WARNING:" in result.stdout and INSTALL in result.stdout


